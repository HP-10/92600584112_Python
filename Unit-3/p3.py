import math

print("=== Mathematical Operations using math module ===")

print("Square root of 25:", math.sqrt(25))
print("Power of 2^3:", math.pow(2, 3))
print("Factorial of 5:", math.factorial(5))
print("Ceiling of 4.3:", math.ceil(4.3))
print("Floor of 4.7:", math.floor(4.7))
print("Absolute value of -10:", math.fabs(-10))
print("GCD of 12 and 18:", math.gcd(12, 18))
print("LCM of 12 and 18:", math.lcm(12, 18))
print("Value of Pi:", math.pi)
print("Value of e:", math.e)
print("Sine of 90 degrees:", math.sin(math.radians(90)))
print("Cosine of 0 degrees:", math.cos(math.radians(0)))
print("Tangent of 45 degrees:", math.tan(math.radians(45)))
print("Log of 10:", math.log(10))